    #[test]
    fn test_chat_event_rpc_tool_call_args_fidelity() {
        // Verify serde_json::Map → serde_json::Value::Object preserves all data.
        let mut args = serde_json::Map::new();
        args.insert("path".into(), serde_json::json!("/tmp/foo.rs"));
        args.insert("recursive".into(), serde_json::json!(true));
        args.insert("depth".into(), serde_json::json!(3));

        let event = {
            let mut e = ChatEvent::default();
            e.stream_id = "s1".into();
            e.event = Some(ChatEventEvent::ToolCall({
                let mut t = ToolCallEvent::default();
                t.call_id = "c1".into();
                t.tool = "read_file".into();
                t.args = args.clone();
                t.requires_approval = false;
                t
            }));
            e
        };
        let rpc = ChatEventRpc::from(&event);
        let json = serde_json::to_value(&rpc).unwrap();
        // All 3 args must survive the conversion.
        assert_eq!(json["args"]["path"], "/tmp/foo.rs");
        assert_eq!(json["args"]["recursive"], true);
        assert_eq!(json["args"]["depth"], 3);
    }

