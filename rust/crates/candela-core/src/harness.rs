//! Domain types, configuration, and errors for the candela-harness IDE sidecar.
//!
//! Session, Message, MessageRole, SearchResult, UsageSummary, and ChatEvent are
//! re-exported from `candela-types` (generated from candela-protos).
//! HarnessConfig, HarnessError, and TransportMode remain harness-specific
//! and are defined here.

use serde::{Deserialize, Serialize};

// ── Re-exported proto-generated types ──

pub use candela_types::session::{Message, MessageRole, SearchResult, Session};

// ── Session constructor ──

/// Extension methods for creating new sessions.
#[allow(clippy::field_reassign_with_default)]
pub fn new_session(model: &str, device_id: &str) -> Session {
    let now = chrono::Utc::now();
    let id = uuid::Uuid::new_v4().to_string();
    let mut session = Session::default();
    session.id = id;
    session.title = "New Chat".to_string();
    session.model = model.to_string();
    session.device_id = device_id.to_string();
    session.created_at = now;
    session.updated_at = now;
    session
}

/// Create a new user message for a session.
#[allow(clippy::field_reassign_with_default)]
pub fn new_message(session_id: &str, role: MessageRole, content: &str) -> Message {
    let mut msg = Message::default();
    msg.id = uuid::Uuid::new_v4().to_string();
    msg.session_id = session_id.to_string();
    msg.role = role;
    msg.content = content.to_string();
    msg.created_at = chrono::Utc::now();
    msg
}

// ── Configuration ──

/// Top-level harness configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct HarnessConfig {
    /// Directory for session storage.
    pub save_dir: std::path::PathBuf,
    /// Candela proxy URL for model routing.
    pub proxy_url: Option<String>,
    /// Default model identifier.
    pub model: String,
    /// Budget limit in USD. 0 = unlimited.
    // TODO: Consider using integer micro-units (i64 microdollars) instead of f64
    // to avoid floating-point rounding in budget calculations.
    pub budget_limit_usd: f64,
    /// Device ID for cross-device sync.
    pub device_id: String,
    /// Enable subagent delegation.
    pub enable_subagents: bool,
    /// Transport mode.
    pub transport: TransportMode,
    /// HTTP port (for daemon mode).
    pub http_port: u16,
    /// Model for auto-generating session titles.
    /// Some("truncate") (default) = first ~80 chars, word-boundary aware.
    /// Some("keywords") = local keyword extraction, no API call.
    /// Some("auto") = resolve cheapest model at runtime via models.list API.
    /// Some("model-name") = use a specific model for LLM summarization.
    /// None = disabled, no auto-titling.
    #[serde(default = "default_auto_title_model")]
    pub auto_title_model: Option<String>,
}

fn default_auto_title_model() -> Option<String> {
    Some("truncate".to_string())
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum TransportMode {
    #[default]
    Stdio,
    Http,
}

impl Default for HarnessConfig {
    fn default() -> Self {
        Self {
            save_dir: std::path::PathBuf::from(".candela/sessions"),
            proxy_url: None,
            model: "gemini-2.0-flash".to_string(),
            budget_limit_usd: 5.0,
            device_id: String::new(),
            enable_subagents: true,
            transport: TransportMode::Stdio,
            http_port: 8200,
            auto_title_model: Some("truncate".to_string()),
        }
    }
}

// ── Errors ──

/// Harness-specific error type.
#[derive(Debug, thiserror::Error)]
pub enum HarnessError {
    #[error("storage error: {0}")]
    Storage(String),

    #[error("serialization error: {0}")]
    Serialization(#[from] serde_json::Error),

    #[error("session not found: {0}")]
    SessionNotFound(String),

    #[error("budget exceeded: used ${used:.4} of ${limit:.4} limit")]
    BudgetExceeded { used: f64, limit: f64 },

    #[error("transport error: {0}")]
    Transport(String),

    #[error("{0}")]
    Other(#[from] anyhow::Error),
}

// ── Streaming Chat Events ──
//
// Two representations of ChatEvent coexist:
//
// 1. `ChatEvent` (struct + oneof) — used internally by the runtime and
//    Connect/gRPC backends. Generated by proto2type `domain` backend.
//
// 2. `ChatEventRpc` (flat tagged enum) — used for JSON-RPC wire format.
//    Generated by proto2type `jsonrpc` backend. Serializes directly to:
//    `{"type":"chunk","stream_id":"...","delta":"..."}`
//
// The From<&ChatEvent> for ChatEventRpc impl lives in candela-types
// (orphan rule requires it there). The handler calls ChatEventRpc::from()
// at the serialization boundary.

pub use candela_types::chat::{
    ChatEvent, ChatEventEvent, ChunkEvent, DoneEvent, ErrorEvent, StatusEvent, ToolCallEvent,
    UsageSummary,
};
pub use candela_types::chat_jsonrpc::ChatEventRpc;

